// Builds src/engine/18-hourschecked.js from tools/places/hours-checked.json: opening hours checked by hand against each
// place's own official website (or the official body that runs it), with the date they were checked. The app reads
// these before the map's hours; each is said on screen with its source, and is treated as not confirmed once it is
// more than a year old. Run: node tools/places/hours-checked-build.cjs
const fs = require('fs'), path = require('path');
const src = JSON.parse(fs.readFileSync(path.join(__dirname, 'hours-checked.json'), 'utf8'));
const keep = src.filter(p => p.name && p.opening_hours).map(p => ({
  city: p.place, name: p.name, aka: (p.aliases || []).filter(a => a && a !== p.name),
  lat: p.lat == null ? undefined : +(+p.lat).toFixed(5), lng: p.lng == null ? undefined : +(+p.lng).toFixed(5),
  oh: p.opening_hours, last: p.last_entry || undefined, url: p.source_url || undefined, by: p.source_kind || undefined,
  checked: p.checked, hol: p.holidays_known ? 1 : undefined, kind: p.kind || undefined, wd: p.wikidata || undefined }));
const out = `// GENERATED by tools/places/hours-checked-build.cjs from tools/places/hours-checked.json. Do not edit by hand.
// Opening hours checked against each place's official website (${keep.length} places).
(function (E) {
  E.CHECKED_HOURS = ${JSON.stringify(keep)};
})(KEngine);
`;
fs.writeFileSync(path.join(__dirname, '..', '..', 'src', 'engine', '18-hourschecked.js'), out);
console.log('wrote', keep.length, 'places,', out.length, 'bytes');
