// Turns the checked story library (stories/<city>/*.json) into the app's recorded stops: writes
// src/features/stop-stories.js, which adds each story to STOP_SCRIPTS (stop-scripts.js), so the app plays it like
// a hand-written script, in the traveler's guide voice, with its sources shown. Only stories that pass
// check-stories.mjs are used. Run: node stories/tools/to-app.mjs   (no AI; the words are the checked words)
import fs from "node:fs"; import crypto from "node:crypto";
const cities = fs.readdirSync("stories").filter(c => fs.existsSync(`stories/${c}/check-report.json`));
// The trip city names a story's place can go by (the stop must also match the sight's own names). Default: the folder.
const CITY = { athens: "Athens|Piraeus", heraklion: "Heraklion|Iraklion|Iraklio", chania: "Chania|Hania|Souda",
  santorini: "Santorini|Thira|Fira", mykonos: "Mykonos", kusadasi: "Kusadasi|Kuşadası|Ephesus|Selcuk|Selçuk|Izmir",
  messina: "Messina|Taormina", naples: "Naples|Napoli|Pompeii|Sorrento|Capri|Pozzuoli|Salerno", rome: "Rome|Roma|Civitavecchia|Vatican" };
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const out = [], say = fs.existsSync("stories/say.json") ? JSON.parse(fs.readFileSync("stories/say.json", "utf8")) : [];
for (const city of cities) {
  const rep = JSON.parse(fs.readFileSync(`stories/${city}/check-report.json`, "utf8"));
  if ((rep.fail || []).length) { console.error(`${city}: the story checks don't pass, so its stories stay out of the app`); continue; }
  const idx = Object.fromEntries(JSON.parse(fs.readFileSync(`stories/${city}/snapshots/index.json`, "utf8")).map(x => [x.key, x]));
  const all = fs.readdirSync(`stories/${city}`).filter(f => /^[a-z].*\.json$/.test(f) && !/^(sources|check-report)\.json$/.test(f))
    .map(f => JSON.parse(fs.readFileSync(`stories/${city}/${f}`, "utf8"))).filter(s => s.parts);
  // A longer name of another story (for example "acropolis museum") is never taken by a shorter one ("acropolis").
  const names = s => s.match.names.map(n => n.toLowerCase());
  for (const st of all) {
    const mine = names(st), longer = all.filter(o => o !== st).flatMap(names).filter(n => mine.some(m => n !== m && n.includes(m)));
    const site = `^(?!.*\\bhotel\\b)${longer.map(n => `(?!.*${esc(n)})`).join("")}.*\\b(${mine.map(esc).join("|")})\\b`;
    const parts = st.parts.map(p => { const paras = p.paras.map(q => q.t), words = paras.join(" ").split(/\s+/).length;
      return { name: p.name, minutes: Math.max(1, Math.round(words / 140)), stand: p.stand || "", paras }; });
    const used = [...new Set(Object.values(st.claims).flatMap(c => c.src))].map(k => idx[k]).filter(Boolean)
      .map(x => ({ pub: x.publisher || "", title: x.title || "", url: String(x.url || "").replace(/^http:\/\//, "https://"), when: String(x.retrieved || "").slice(0, 10) }));
    const v = st.v + "-" + crypto.createHash("sha1").update(JSON.stringify(parts)).digest("hex").slice(0, 6);
    out.push({ id: `${city}-${st.id}`, v, city: CITY[city] || city, site, title: st.title, where: st.title, checked: st.checked, parts, sources: used });
  }
}
const re = s => `/${s.replace(/\//g, "\\/")}/i`;
const js = `// Generated by stories/tools/to-app.mjs from the checked story library (stories/). Do not edit by hand: change the
// story, run the checks, then run the tool again. Each story plays like a hand-written script (stop-scripts.js), in the
// traveler's guide voice, and shows where its facts come from.
SAY.push(${say.map(([a, b]) => `[/\\b${esc(a)}\\b/g, ${JSON.stringify(b)}]`).join(", ")});
STOP_SCRIPTS.push(
${out.map(s => `  { id: ${JSON.stringify(s.id)}, v: ${JSON.stringify(s.v)}, city: ${re(s.city)}, site: ${re(s.site)}, title: ${JSON.stringify(s.title)}, where: ${JSON.stringify(s.where)}, checked: ${JSON.stringify(s.checked)},
    sources: ${JSON.stringify(s.sources)},
    parts: ${JSON.stringify(s.parts)} }`).join(",\n")}
);
`;
fs.writeFileSync("src/features/stop-stories.js", js);
console.log(`${out.length} stories written to src/features/stop-stories.js`);
